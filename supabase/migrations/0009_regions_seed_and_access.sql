-- ============================================================================
-- YINSEA 后台管理系统 — 地区管理 V1：预置地区 + 代理商读取权限收紧
-- ============================================================================
-- 目的：
--   1. 幂等地新增「曼谷 / 苏梅岛 / 芭提雅」三个地区，供管理员在
--      「系统设置 → 地区管理」中直接看到并管理，默认启用。
--   2. 代理商只能读取 is_active = true 的地区（与 0007 对 categories 的
--      收紧方式一致），停用的地区不会出现在代理商的地区筛选中。
--
-- 严格限制（本迁移只做以下变更）：
--   - 不修改现有 phuket 行的任何字段（不在本迁移的 insert 列表中）；
--   - 不新建、不删除、不修改字段；不涉及 regions 表结构；
--   - 不修改、不迁移、不删除任何 products 数据；现有产品的 region_id
--     完全不受影响，仍然是各自原来的地区（现有 72 个产品继续保持普吉岛）；
--   - 不改动 regions_admin_all（管理员仍可读取全部地区，包括停用的）；
--   - 不改动 categories、products 或其他任何表的策略。
-- 可安全重复执行。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 幂等新增三个地区（默认启用）。
--    使用 on conflict (slug) do nothing：如果这些地区已经存在（无论是本迁移
--    之前执行过，还是管理员后来手动编辑过），一律不覆盖、不改动。
--    phuket 完全不出现在下面的 values 中，因此不会被本迁移触碰。
-- ---------------------------------------------------------------------------
insert into public.regions (slug, name, name_en, sort_order, is_active)
values
  ('bangkok',   '曼谷',   'Bangkok',   2, true),
  ('koh-samui', '苏梅岛', 'Koh Samui', 3, true),
  ('pattaya',   '芭提雅', 'Pattaya',   4, true)
on conflict (slug) do nothing;

-- ---------------------------------------------------------------------------
-- 2. 收紧代理商（及其他非管理员的已登录用户）对 regions 的读取权限：
--    在原有「已登录且账号启用」的基础上，新增「is_active = true」条件。
--    管理员完全不受影响，仍通过 regions_admin_all 读取全部地区。
-- ---------------------------------------------------------------------------
drop policy if exists regions_active_user_read on public.regions;

create policy regions_active_user_read on public.regions for select
  using (public.is_logged_in_active() and is_active = true);

-- ============================================================================
-- 完成后：
--   - regions 表中应能看到 phuket（未改动）、bangkok、koh-samui、pattaya 共 4 条；
--   - 管理员在「系统设置 → 地区管理」可见并管理全部 4 个地区；
--   - 代理商的地区筛选只会看到 is_active = true 的地区；
--   - products 表不受任何影响，现有 72 个产品的 region_id 保持不变。
-- ============================================================================
